package gen

import (
	"io"
	"text/template"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
)

// Options are the options to set for rendering the template.
type Options struct {
	EnumsAsInts        bool
	EmitDefaults       bool
	EmitDefaultValues  bool
	OrigName           bool
	AllowUnknownFields bool
	EmitScannerValuer  bool
	EmitJSONV2         bool
}

// ApplyTemplate writes the JSON methods for all messages in f to g.
func ApplyTemplate(g *protogen.GeneratedFile, f *protogen.File, opts *Options) error {
	const (
		syntaxFieldNumber  = 12
		packageFieldNumber = 2
	)
	genStandaloneComments(g, f, syntaxFieldNumber)
	g.P("// Code generated by protoc-gen-go-json. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	genStandaloneComments(g, f, packageFieldNumber)
	if err := headerTemplate.Execute(g, tplHeader{
		File:    f,
		Options: opts,
	}); err != nil {
		return err
	}
	return applyMessages(g, f.Messages, opts)
}

// ApplyJSONV2Template writes the encoding/json/v2 streaming methods for all
// messages in f to g. The methods call github.com/protolayer/protojsonx-go,
// which needs Go 1.27 or newer.
func ApplyJSONV2Template(g *protogen.GeneratedFile, f *protogen.File, opts *Options) error {
	const syntaxFieldNumber = 12
	genStandaloneComments(g, f, syntaxFieldNumber)
	g.P("// Code generated by protoc-gen-go-json. DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	if err := jsonV2HeaderTemplate.Execute(g, tplHeader{
		File:    f,
		Options: opts,
	}); err != nil {
		return err
	}
	return applyMessagesWith(g, jsonV2MessageTemplate, f.Messages, opts)
}

func applyMessages(w io.Writer, msgs []*protogen.Message, opts *Options) error {
	return applyMessagesWith(w, messageTemplate, msgs, opts)
}

func applyMessagesWith(w io.Writer, tpl *template.Template, msgs []*protogen.Message, opts *Options) error {
	for _, m := range msgs {
		if m.Desc.IsMapEntry() {
			continue
		}
		if err := tpl.Execute(w, tplMessage{
			Message: m,
			Options: opts,
		}); err != nil {
			return err
		}
		if err := applyMessagesWith(w, tpl, m.Messages, opts); err != nil {
			return err
		}
	}
	return nil
}

type tplHeader struct {
	*protogen.File
	*Options
}

type tplMessage struct {
	*protogen.Message
	*Options
}

